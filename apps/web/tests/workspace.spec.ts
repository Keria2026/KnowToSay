import { test, expect } from '@playwright/test';
import { resolve } from 'node:path';

test('创建工作组、分支导航、复制、悬浮布局、Excel 导入搜索与发布', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'连接你的工作组'})).toBeVisible();
  await page.getByRole('button',{name:'创建工作组',exact:true}).click();
  await page.getByLabel('工作组名称').fill('销售验收工作组');
  await page.getByRole('button',{name:'创建并进入工作台'}).click();
  await expect(page.getByRole('heading',{name:'从一条好话术开始'})).toBeVisible();
  await page.getByRole('button',{name:'体验示例流程'}).click();
  await expect(page.getByRole('heading',{name:'开场问候',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'复制回复',exact:true})).toBeDisabled();
  await page.getByLabel('客户姓名').fill('지민');
  await page.getByRole('button',{name:'复制回复',exact:true}).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('지민님');
  await page.getByRole('button',{name:'吃了',exact:true}).click();
  await expect(page.getByRole('heading',{name:'已经用餐',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'继续介绍',exact:true}).click();
  await expect(page.getByRole('heading',{name:'介绍产品',exact:true})).toBeVisible();
  await page.getByLabel('价格').fill('₩20,000');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({path:testInfo.outputPath('workbench.png'),fullPage:true});
  await page.getByRole('button',{name:'切换悬浮窗口'}).click();
  await page.setViewportSize({width:400,height:850});
  await expect(page.getByText('精简布局预览',{exact:true})).toBeVisible();
  await expect(page.getByLabel('价格')).toHaveValue('₩20,000');
  await page.evaluate(() => window.scrollTo(0, 0));
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0);
  const toolbar = await page.locator('.topbar').boundingBox();
  const heading = await page.locator('.compact-heading').boundingBox();
  expect(toolbar).not.toBeNull();
  expect(heading).not.toBeNull();
  expect(heading!.y).toBeGreaterThanOrEqual(toolbar!.y + toolbar!.height);
  await page.screenshot({path:testInfo.outputPath('compact.png'),fullPage:true});
  await page.getByRole('button',{name:'切换完整窗口'}).click();
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'知识库',exact:true}).click();
  await page.getByRole('button',{name:'新建分类',exact:true}).click();
  await page.getByLabel('分类名称',{exact:true}).fill('配送与售后');
  await page.screenshot({path:testInfo.outputPath('new-category.png'),fullPage:true});
  await page.getByRole('button',{name:'创建分类',exact:true}).click();
  await expect(page.getByRole('heading',{name:'此分类还没有素材'})).toBeVisible();
  await expect(page.getByLabel('筛选分类')).toHaveValue('配送与售后');
  await page.reload();
  await page.getByRole('button',{name:'知识库',exact:true}).click();
  await page.getByLabel('筛选分类').selectOption('配送与售后');
  await expect(page.getByRole('heading',{name:'此分类还没有素材'})).toBeVisible();
  await page.getByRole('button',{name:'新建分类',exact:true}).click();
  await page.getByLabel('分类名称',{exact:true}).fill('配送与售后');
  await page.getByRole('button',{name:'创建分类',exact:true}).click();
  await expect(page.getByRole('alert')).toHaveText('此分类已存在');
  await page.getByRole('button',{name:'取消',exact:true}).click();
  await page.getByRole('button',{name:'文字素材',exact:true}).click();
  await expect(page.getByLabel('分类',{exact:true})).toHaveValue('配送与售后');
  await page.getByLabel('名称',{exact:true}).fill('售后答复');
  await page.getByLabel('正文',{exact:true}).fill('请提供订单信息，我们会协助您核实。');
  await page.getByRole('button',{name:'保存到草稿',exact:true}).click();
  await expect(page.getByRole('heading',{name:'售后答复',exact:true})).toBeVisible();
  await page.locator('input[type=file]').setInputFiles(resolve('apps/web/static/script-template.xlsx'));
  await expect(page.getByRole('heading',{name:'script-template.xlsx'})).toBeVisible();
  await page.getByRole('button',{name:'导入为话术'}).click();
  await page.getByRole('button',{name:'预览并校验'}).click();
  await expect(page.getByText('校验通过，共 4 条，预览前 20 条')).toBeVisible();
  await page.getByRole('button',{name:'确认导入 4 条'}).click();
  await expect(page.getByRole('button',{name:'确认导入 4 条'})).toBeHidden();
  await page.getByRole('textbox',{name:'全局搜索'}).fill('식사');
  await expect(page.locator('.excel-hit').first()).toContainText('话术');
  await page.screenshot({path:testInfo.outputPath('search.png'),fullPage:true});
  await page.getByRole('button',{name:'清空搜索'}).click();
  await page.getByRole('button',{name:'话术与流程',exact:false}).click();
  await expect(page.getByText('8 个步骤 · 8 条连接')).toBeVisible();
  await page.getByRole('tab',{name:/快捷话术/}).click();
  await page.getByRole('button',{name:'新建快捷话术',exact:true}).click();
  await page.getByLabel('题目',{exact:true}).fill('客户说太贵了');
  await page.getByLabel('客户问题 / 特定回复',{exact:true}).fill('客户认为价格太高');
  await page.getByLabel('한국어 · 韩语',{exact:true}).fill('가격에는 제품과 서비스가 포함되어 있습니다.');
  await page.getByLabel('简体中文',{exact:true}).fill('价格包含产品与服务，我可以为您介绍具体内容。');
  await expect(page.getByLabel('作为流程入口')).toHaveCount(0);
  await expect(page.getByRole('heading',{name:'下一步分支',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'保存话术',exact:true}).click();
  await expect(page.locator('.script-library-list').getByText('客户说太贵了',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'新建快捷话术',exact:true}).click();
  await page.getByLabel('题目',{exact:true}).fill('咨询产品信息');
  await page.getByLabel('客户问题 / 特定回复',{exact:true}).fill('客户想了解某个产品');
  await page.getByLabel('한국어 · 韩语',{exact:true}).fill('관심 상품은 {产品名}입니다.');
  await page.getByRole('button',{name:'保存话术',exact:true}).click();
  await expect(page.locator('.script-library-list').getByText('咨询产品信息',{exact:true})).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('quick-script-management.png'),fullPage:true});
  await page.getByRole('tab',{name:/流程话术/}).click();
  await expect(page.getByText('8 个步骤 · 8 条连接')).toBeVisible();
  await expect(page.locator('.svelte-flow__node').filter({hasText:'客户说太贵了'})).toHaveCount(0);
  await page.getByRole('textbox',{name:'全局搜索'}).fill('价格太高');
  await page.locator('.search-result').filter({hasText:'客户说太贵了'}).click();
  await expect(page.getByRole('heading',{name:'客户说太贵了',exact:true})).toBeVisible();
  await expect(page.getByText('当前流程已到此处',{exact:true})).toHaveCount(0);

  await page.getByRole('button',{name:'发布与同步',exact:true}).click();
  await page.getByRole('button',{name:'发布更新',exact:true}).click();
  await expect(page.getByText('当前已发布版本 v1 · 草稿不会自动同步')).toBeVisible();
  await page.reload();
  await expect(page.getByText('销售验收工作组').first()).toBeVisible();
  await expect(page.getByRole('heading',{name:'开场问候',exact:true})).toBeVisible();
  // The packaged search window must load the production SPA root, not /index.html.
  await page.setViewportSize({width:720,height:560});
  await page.goto('http://127.0.0.1:1423/?quickSearch=1&panel=quick');
  await expect(page.getByRole('heading',{name:'快捷话术回复表',exact:true})).toBeVisible();
  await expect(page.locator('.quick-reply-table')).toContainText('客户说太贵了');
  await expect(page.locator('.quick-reply-table')).not.toContainText('开场问候');
  await page.getByRole('button',{name:'复制客户说太贵了',exact:true}).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('가격에는 제품과 서비스가 포함되어 있습니다.');
  await page.getByRole('button',{name:'查看咨询产品信息',exact:true}).click();
  await expect(page.getByRole('button',{name:'复制回复',exact:true})).toBeDisabled();
  await page.getByLabel('产品名',{exact:true}).fill('크림');
  await page.getByRole('button',{name:'复制回复',exact:true}).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('관심 상품은 크림입니다.');
  await page.getByLabel('独立搜索发送语言').selectOption('zh-CN');
  await expect(page.getByRole('button',{name:'复制回复',exact:true})).toBeDisabled();
  await expect(page.getByText('暂无此语言版本，请选择其他语言。')).toBeVisible();
  await page.getByLabel('独立搜索发送语言').selectOption('ko');
  await page.getByRole('button',{name:'返回回复表',exact:true}).click();
  await page.getByRole('textbox',{name:'独立搜索栏',exact:true}).fill('价格太高');
  await expect(page.locator('.quick-reply-table tbody tr')).toHaveCount(1);
  await page.screenshot({path:testInfo.outputPath('quick-replies.png'),fullPage:true});
  await page.getByRole('button',{name:'全库搜索',exact:true}).click();
  await page.getByRole('textbox',{name:'独立搜索栏',exact:true}).fill('开场问候');
  await page.locator('.quick-result').first().click();
  await page.getByLabel('客户姓名').fill('민수');
  await page.getByRole('button',{name:'复制回复',exact:true}).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('민수님');
  await page.screenshot({path:testInfo.outputPath('quick-search.png'),fullPage:true});
  await page.getByRole('button',{name:'在工作台打开'}).click();
  await expect(page.getByRole('heading',{name:'开场问候',exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});
